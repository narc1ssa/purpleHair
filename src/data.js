export const platforms = Object.entries(paths).map(([id, points]) => ({
  id,
  points,
  left: points[0][0],
  right: points.at(-1)[0],
}));
export const platformById = Object.fromEntries(platforms.map((p) => [p.id, p]));
export function surface(p, x) {
  const a = p.points;
  for (let i = 1; i < a.length; i++)
    if (x <= a[i][0]) {
      const t = clamp((x - a[i - 1][0]) / (a[i][0] - a[i - 1][0]), 0, 1);
      return a[i - 1][1] + (a[i][1] - a[i - 1][1]) * t;
    }
  return a.at(-1)[1];
}

